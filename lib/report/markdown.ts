/** Markdown renderings of an analysis and of an equivalence run. */
import type { ProgramExplanation } from "../ai/types";
import type { SystemAnalysis } from "../cobol/analyze";
import type { VerificationRun } from "../index";
import { CATEGORY_LABEL } from "../verify/runtime";

const n = (x: number) => x.toLocaleString("en-US");
const cell = (s: unknown) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

export function analysisMarkdown(sys: SystemAnalysis, explanations: Map<string, ProgramExplanation> = new Map()): string {
  const t = sys.totals;
  const L: string[] = [];
  L.push("# Mue analysis", "");
  L.push(`${t.programs} programs, ${t.copybooks} copybooks, ${t.jobs} JCL jobs, ${n(t.lines)} lines (${n(t.codeLines)} lines of code), ${t.tables} DB2 tables. Cumulative cyclomatic complexity: ${t.complexity}. Dead paragraphs: ${t.deadParagraphs}. Constructs needing manual work: ${t.manualItems}.`, "");

  L.push("## Inventory", "");
  L.push("| Program | Kind | Lines | Code | Complexity | Calls | Called by | Tables (R/W) | Dead code | Manual work |");
  L.push("|---|---|---:|---:|---:|---|---|---|---|---|");
  for (const p of sys.programs) {
    const kind = p.isSubprogram ? "subprogram" : p.isBatch ? "batch" : "program";
    const tables = p.tables.map((x) => `${x.name} ${x.read && x.write ? "R/W" : x.write ? "W" : "R"}`).join(", ");
    L.push(`| ${p.id} | ${kind} | ${p.lines.total} | ${p.lines.code} | ${p.complexity} | ${cell([...new Set(p.calls.map((c) => c.program))].join(", "))} | ${cell([...p.calledBy, ...p.jobs.map((j) => `job ${j}`)].join(", "))} | ${cell(tables)} | ${cell(p.deadParagraphs.join(", "))} | ${cell([...new Set(p.manual.map((m) => m.construct))].join(", "))} |`);
  }
  L.push("");

  L.push("## Call graph", "");
  L.push("```mermaid", "flowchart LR");
  const id = (s: string) => s.replace(/[^A-Za-z0-9_]/g, "_");
  for (const node of sys.graph.nodes) {
    const label = node.label;
    const shape = node.type === "table" ? `[(${label})]` : node.type === "job" ? `{{${label}}}` : node.type === "copybook" ? `[/${label}/]` : node.type === "external" ? `[${label} ?]` : `[${label}]`;
    L.push(`  ${id(node.id)}${shape}`);
  }
  const arrow: Record<string, string> = { exec: "-->|runs|", call: "-->|CALL|", copy: "-.->|COPY|", read: "-->|reads|", write: "==>|writes|" };
  for (const e of sys.graph.edges) L.push(`  ${id(e.source)} ${arrow[e.kind]} ${id(e.target)}`);
  L.push("```", "");
  if (sys.missingPrograms.length) L.push(`Not in the sources: ${sys.missingPrograms.map((m) => `${m.name} (called by ${m.calledBy.join(", ")})`).join("; ")}.`, "");

  if (sys.tables.length) {
    L.push("## DB2 tables", "", "| Table | Read by | Written by |", "|---|---|---|");
    for (const x of sys.tables) L.push(`| ${x.name} | ${x.readers.join(", ")} | ${x.writers.join(", ")} |`);
    L.push("");
  }
  if (sys.copybooks.length) {
    L.push("## Copybooks", "", "| Copybook | Lines | Used by |", "|---|---:|---|");
    for (const c of sys.copybooks) L.push(`| ${c.name} | ${c.lines} | ${c.usedBy.join(", ") || "(unused)"} |`);
    L.push("");
  }

  L.push("## Programs", "");
  for (const p of sys.programs) {
    const e = explanations.get(p.id);
    L.push(`### ${p.id}${p.title ? ` · ${cell(p.title.charAt(0) + p.title.slice(1).toLowerCase())}` : ""}`, "");
    if (e) {
      L.push(e.role, "");
      if (e.rules.length) {
        L.push("Business rules:", "");
        for (const r of e.rules) L.push(`${r.n}. ${r.text} _(line ${r.line}${r.endLine > r.line ? `–${r.endLine}` : ""})_`);
        L.push("");
      }
      if (e.attention.length) {
        L.push("Points of attention:", "");
        for (const a of e.attention) L.push(`- ${a.level === "warn" ? "**Warning:** " : ""}${a.text}${a.line ? ` _(line ${a.line})_` : ""}`);
        L.push("");
      }
    }
    if (p.diagnostics.length) {
      L.push("Parser diagnostics:", "");
      for (const d of p.diagnostics) L.push(`- ${d.severity}: ${d.message} _(line ${d.line}${d.file ? `, ${d.file}` : ""})_`);
      L.push("");
    }
  }
  return L.join("\n");
}

export function verificationMarkdown(run: VerificationRun): string {
  const t = run.totals;
  const L: string[] = [];
  L.push("# Mue equivalence report", "");
  const verdict = t.mismatch ? "MISMATCHES FOUND" : t.equivalent ? "EQUIVALENT" : "NOTHING VERIFIED";
  L.push(`**${verdict}.** ${t.equivalent} of ${t.programs} programs proven equivalent on ${n(t.cases)} replayed cases (${n(t.identical)} identical, ${n(t.mismatches)} different). ${t.skipped ? `${t.skipped} skipped because they contain constructs that are not converted automatically.` : ""}`.trim(), "");
  L.push(`Generated by ${run.tool.name} ${run.tool.version} on ${run.createdAt}. Conventions: rounding ${run.conventions.rounding}, overflow ${run.conventions.overflow}${Object.keys(run.overrides).length ? `; overrides: ${Object.entries(run.overrides).map(([p, o]) => `${p} ${JSON.stringify(o)}`).join(", ")}` : ""}.`, "");

  L.push("| Program | Java class | Status | Cases | Identical | Mismatches |", "|---|---|---|---:|---:|---:|");
  for (const p of run.programs) L.push(`| ${p.program} | ${p.className ?? ""} | ${p.status} | ${p.report ? n(p.report.total) : "–"} | ${p.report ? n(p.report.identical) : "–"} | ${p.report ? n(p.report.mismatches) : "–"} |`);
  L.push("");

  for (const p of run.programs) {
    if (p.status === "skipped") {
      L.push(`## ${p.program}: skipped`, "", p.reason ?? "", "");
      continue;
    }
    const r = p.report!;
    L.push(`## ${p.program}: ${p.status === "equivalent" ? "equivalent" : `${n(r.mismatches)} mismatches`}`, "");
    L.push(`${n(r.total)} cases, seed ${r.seed}, ${r.durationMs} ms. Inputs: ${r.inputs.join(", ") || "none"}${r.selects.length ? `; SQL SELECT results: ${r.selects.join(", ")}` : ""}${r.cursors.length ? `; cursors: ${r.cursors.join(", ")}` : ""}. Compared outputs: ${r.outputs.join(", ")}, plus SQL writes, external calls and DISPLAY lines.`, "");
    L.push("| Case category | Cases | Mismatches |", "|---|---:|---:|");
    for (const c of r.byCategory) L.push(`| ${CATEGORY_LABEL[c.category]} | ${n(c.total)} | ${c.mismatches} |`);
    L.push("");
    r.groups.forEach((g, i) => {
      const ex = p.explanations[i];
      L.push(`### ${ex?.title ?? g.kind} (${g.count} cases)`, "");
      L.push(`First divergence: ${g.program} line ${g.line}, field ${g.field}${g.pic ? ` (PIC ${g.pic})` : ""}${g.javaMode ? `, Java RoundingMode.${g.javaMode}` : ""}.`, "");
      if (ex) L.push(ex.explanation, "");
      if (g.examples.length) {
        L.push("| Case | Exact value | COBOL | Java |", "|---|---:|---:|---:|");
        for (const x of g.examples) L.push(`| #${x.caseId} | ${x.raw ?? "–"} | ${x.cobol} | ${x.java} |`);
        L.push("");
      }
      if (ex?.fix) L.push(`Suggested fix: ${ex.fix.label}${ex.fix.kind === "rounding" ? ` (CLI: \`--fix ${ex.fix.program}=${ex.fix.value}\`)` : ""}.`, "");
    });
    if (r.warnings.length) {
      L.push("Legacy behaviors reproduced exactly:", "");
      for (const w of r.warnings) L.push(`- **${w.title}** (${w.count} cases${w.line ? `, ${w.program} line ${w.line}` : ""}). ${w.detail}`);
      L.push("");
    }
  }
  const model = run.programs.find((p) => p.report)?.report?.model;
  if (model) L.push("## Method", "", `- COBOL reference: ${model.cobol}`, `- Java: ${model.java}`, "- Database reads and programs missing from the sources are stubbed identically on both sides; only the converted code is compared.", "");
  return L.join("\n");
}
